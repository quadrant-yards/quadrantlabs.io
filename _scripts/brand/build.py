# ── helpers ──────────────────────────────────────────────────────────────

def luminance(hex_color: str) -> float:
    h = hex_color.lstrip("#")
    channels = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]


def contrast(a: str, b: str) -> float:
    la, lb = luminance(a), luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def inline_html(text: str) -> str:
    """Escape, then apply `code`, **bold**, [label](url)."""
    out = html.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', out)
    return out


def fmt(n: float) -> str:
    return f"{n:g}"


# ── load + validate ──────────────────────────────────────────────────────

def load():
    data = tomllib.loads((HERE / "brand.toml").read_text())
    wordmark = json.loads((HERE / "wordmark.json").read_text())
    google_url = data["fonts"]["google_url"]
    for sec in data["section"]:
        sec["rules"] = [r.replace("{google_url}", google_url) for r in sec.get("rules", [])]
    return data, wordmark


def check_contrast(colors: dict) -> list[dict]:
    """Return one row per checked pair; raise if any fails."""
    rows, failures = [], []
    for token, c in colors.items():
        for mode in ("light", "dark"):
            if c["kind"] == "text":
                for bg in ("paper", "surface"):
                    rows.append((token, mode, bg, contrast(c[mode], colors[bg][mode]), 4.5))
            elif c["kind"] == "fill":
                rows.append((c["on"], mode, token, contrast(colors[c["on"]][mode], c[mode]), 4.5))
            elif "min_contrast" in c:
                rows.append((token, mode, "paper", contrast(c[mode], colors["paper"][mode]), c["min_contrast"]))
    result = []
    for fg, mode, bg, ratio, need in rows:
        result.append(dict(fg=fg, bg=bg, mode=mode, ratio=round(ratio, 2), min=need))
        if ratio < need:
            failures.append(f"{fg} on {bg} ({mode}): {ratio:.2f} < {need}")
    if failures:
        raise SystemExit("Contrast check failed:\n  " + "\n  ".join(failures))
    return result


def ratio_summary(token: str, colors: dict, checks: list[dict]) -> str:
    """Short contrast note for a token's row, e.g. 'light 7.1 · dark 9.8'."""
    c = colors[token]
    if c["kind"] == "text":
        pick = [x for x in checks if x["fg"] == token]
    elif c["kind"] == "fill":
        pick = [x for x in checks if x["bg"] == token]
    else:
        pick = [x for x in checks if x["fg"] == token]
    if not pick:
        return ""
    by_mode = {}
    for x in pick:
        by_mode[x["mode"]] = min(by_mode.get(x["mode"], 99), x["ratio"])
    return " · ".join(f"{m} {by_mode[m]:.1f}:1" for m in ("light", "dark") if m in by_mode)


# ── tokens.css / base.css / tokens.json ──────────────────────────────────

def css_vars(data: dict, mode: str) -> list[str]:
    lines = [f"  --q-{t}: {c[mode]};" for t, c in data["colors"].items()]
    lines.append(f"  --q-shadow: {data['layout']['shadow_' + mode]};")
    return lines


def build_tokens_css(data: dict) -> str:
    m, lay = data["meta"], data["layout"]
    static = []
    for role, f in data["fonts"].items():
        if isinstance(f, dict):
            static.append(f"  --q-font-{role}: {f['stack']};")
    for t in data["type"]:
        static.append(f"  --q-text-{t['token']}: {fmt(t['size'])}rem;")
        static.append(f"  --q-leading-{t['token']}: {fmt(t['leading'])};")
    for i, px in enumerate(lay["space"], start=1):
        static.append(f"  --q-space-{i}: {px}px;")
    static += [
        f"  --q-radius-sm: {lay['radius_sm']}px;",
        f"  --q-radius-md: {lay['radius_md']}px;",
        f"  --q-radius-pill: {lay['radius_pill']}px;",
        f"  --q-measure: {lay['measure']};",
        f"  --q-page-max: {lay['page_max']};",
        f"  --q-motion: {lay['motion']};",
    ]
    light, dark = css_vars(data, "light"), css_vars(data, "dark")
    return "\n".join([
        f"/* Quadrant brand tokens v{m['version']} ({m['updated']}). {m['url']}",
        f"   {GENERATED}",
        "   Fonts: " + data["fonts"]["google_url"],
        "   Dark mode follows the OS; force it with <html data-theme=\"light|dark\">. */",
        "",
        ":root {",
        *static,
        "",
        *light,
        "  color-scheme: light;",
        "}",
        "",
        "@media (prefers-color-scheme: dark) {",
        "  :root:not([data-theme=\"light\"]) {",
        *["  " + x for x in dark],
        "    color-scheme: dark;",
        "  }",
        "}",
        "",
        ":root[data-theme=\"dark\"] {",
        *dark,
        "  color-scheme: dark;",
        "}",
        "",
    ])


