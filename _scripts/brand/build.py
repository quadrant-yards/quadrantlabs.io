def build_all() -> dict[str, str]:
    data, wm = load()
    checks = check_contrast(data["colors"])
    files = {
        "tokens.css": build_tokens_css(data),
        "base.css": build_base_css(data),
        "tokens.json": build_tokens_json(data, checks),
        "llms.txt": build_llms(data, checks),
        "index.html": build_index(data, wm, checks),
    }
    files.update(build_assets(data, wm))
    return files


def main() -> None:
    check = "--check" in sys.argv
    files = build_all()
    stale = []
    for rel, content in files.items():
        path = OUT / rel
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if check:
        if stale:
            sys.exit("brand/ is out of date. Run python3 _scripts/brand/build.py\n  " + "\n  ".join(stale))
        print(f"brand/ is up to date ({len(files)} files).")
    else:
        print(f"Wrote {len(files)} files to {OUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
