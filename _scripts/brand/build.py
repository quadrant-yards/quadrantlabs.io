def build_llms(data: dict, checks: list[dict]) -> str:
    m, colors, lay = data["meta"], data["colors"], data["layout"]
    base = m["url"]
    L = [
        f"# {m['name']} brand guide",
        "",
        f"> {m['summary']}",
        "",
        f"Version {m['version']}, updated {m['updated']}. Canonical URL: {base}llms.txt",
        f"Human version: {base} · {GENERATED}",
        "",
        m["story"],
        "",
        "## Files",
        "",
        f"- [tokens.css]({base}tokens.css): CSS custom properties (`--q-*`), light + dark. Copy into the project.",
        f"- [base.css]({base}base.css): optional element defaults and classes `.q-btn`, `.q-btn-primary`, `.q-input`, `.q-card`, `.q-pill`, `.q-pill-signal`, `.q-kicker`, `.q-num`.",
        f"- [tokens.json]({base}tokens.json): the same tokens for non-CSS tools.",
    ]
    for name, note in ASSET_NOTES.items():
        L.append(f"- [assets/{name}]({base}assets/{name}): {note}")
    L.append("")

    for sec in data["section"]:
        L += [f"## {sec['title']}", ""]
        if sec.get("intro"):
            L += [sec["intro"], ""]

        if sec["id"] == "color":
            L += ["| Token | CSS variable | Name | Role | Light | Dark | Contrast |",
                  "|---|---|---|---|---|---|---|"]
            for t, c in colors.items():
                L.append(f"| `{t}` | `--q-{t}` | {c.get('name', '')} | {c['role']} | `{c['light']}` | `{c['dark']}` | {ratio_summary(t, colors, checks)} |")
            L += ["", "Contrast is the lowest ratio against `paper` and `surface` (text), or of the `on-*` color on the fill. Minimum 4.5:1 for text, 3:1 for `secondary` graphics.", ""]

        if sec["id"] == "type":
            L += ["| Role | Font | Weights | CSS variable | Use |", "|---|---|---|---|---|"]
            for role, f in data["fonts"].items():
                if isinstance(f, dict):
                    L.append(f"| {role} | {f['family']} | {', '.join(map(str, f['weights']))} | `--q-font-{role}` | {f['use']} |")
            L += ["", "| Token | Size | Line height | Font | Use |", "|---|---|---|---|---|"]
            for t in data["type"]:
                L.append(f"| `{t['token']}` | {fmt(t['size'])}rem ({fmt(t['size'] * 16)}px) | {fmt(t['leading'])} | {t['font']} | {t['use']} |")
            L += ["", "CSS: `--q-text-<token>` (size) and `--q-leading-<token>` (line height).", ""]

        if sec["id"] == "layout":
            sp = ", ".join(f"`--q-space-{i}` {px}px" for i, px in enumerate(lay["space"], 1))
            L += [f"Tokens: {sp}; `--q-radius-sm` {lay['radius_sm']}px, `--q-radius-md` {lay['radius_md']}px, "
                  f"`--q-radius-pill`; `--q-measure` {lay['measure']}; `--q-page-max` {lay['page_max']}; "
                  f"`--q-shadow`; `--q-motion` {lay['motion']}.", ""]

        for r in sec.get("rules", []):
            L.append(f"- {r}")
        if sec.get("rules"):
            L.append("")
        if sec.get("dont"):
            L.append("Don't:")
            L += [f"- {d}" for d in sec["dont"]]
            L.append("")
        if sec.get("words_use"):
            L += ["Words that fit: " + ", ".join(sec["words_use"]) + ".", ""]
        if sec.get("words_avoid"):
            L += ["Words to avoid: " + ", ".join(sec["words_avoid"]) + ".", ""]
        for ex in sec.get("examples", []):
            L += [f"- {ex['context']}. Instead of: \"{ex['before']}\" Write: \"{ex['after']}\""]
        if sec.get("examples"):
            L.append("")
        if sec.get("snippet"):
            L += ["Snippet for CLAUDE.md / AGENTS.md:", "", "```markdown", sec["snippet"], "```", ""]
        if sec.get("checklist"):
            L.append("Checklist before shipping UI, copy, or assets:")
            L += [f"- [ ] {x}" for x in sec["checklist"]]
            L.append("")
    return "\n".join(L).rstrip() + "\n"


