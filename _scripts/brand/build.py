def build_base_css(data: dict) -> str:
    return BASE_CSS.replace("{version}", data["meta"]["version"]).replace("{generated}", GENERATED)


def build_tokens_json(data: dict, checks: list[dict]) -> str:
    lay = data["layout"]
    out = {
        "$comment": GENERATED,
        "meta": data["meta"],
        "color": {t: {k: v for k, v in c.items()} for t, c in data["colors"].items()},
        "contrast": checks,
        "font": {r: f for r, f in data["fonts"].items() if isinstance(f, dict)},
        "font_url": data["fonts"]["google_url"],
        "type": data["type"],
        "space_px": lay["space"],
        "radius_px": {"sm": lay["radius_sm"], "md": lay["radius_md"], "pill": lay["radius_pill"]},
        "measure": lay["measure"],
        "page_max": lay["page_max"],
        "shadow": {"light": lay["shadow_light"], "dark": lay["shadow_dark"]},
        "motion": lay["motion"],
    }
    return json.dumps(out, indent=2) + "\n"


# ── logo assets ──────────────────────────────────────────────────────────

def mark_shapes(logo: dict, color: str) -> str:
    x1, y1, x2, y2 = logo["mark_line"]
    w = logo["stroke"]
    return (
        f'<path d="{logo["mark_path"]}" stroke="{color}" stroke-width="{w}" stroke-linejoin="miter" fill="none"/>'
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{color}" stroke-width="{w}" stroke-linecap="round"/>'
    )


def svg_mark(logo: dict, color: str, title: str = "Quadrant") -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="90" height="78" viewBox="{logo["mark_viewbox"]}" fill="none" role="img">'
        f"<title>{title}</title>{mark_shapes(logo, color)}</svg>\n"
    )


def svg_favicon(logo: dict, bg: str, line: str) -> str:
    x1, y1, x2, y2 = logo["mark_line"]
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="90" height="78" viewBox="{logo["mark_viewbox"]}" role="img"><title>Quadrant</title>'
        f'<path d="{logo["mark_path"]}" fill="{bg}" stroke="{bg}" stroke-width="2" stroke-linejoin="miter"/>'
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{line}" stroke-width="6" stroke-linecap="round"/></svg>\n'
    )


def svg_app_icon(logo: dict, bg: str, fg: str) -> str:
    # Full-bleed square (platforms apply their own mask); mark sits inside the 80% safe zone.
    s = 2.9
    tx = 256 - 50 * s
    ty = 256 - 44 * s  # mark's visual centre is about y=44 in its own units
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="512" height="512" viewBox="0 0 512 512" role="img"><title>Quadrant</title>'
        f'<rect width="512" height="512" fill="{bg}"/>'
        f'<g transform="translate({tx:.1f} {ty:.1f}) scale({s})" fill="none">{mark_shapes(logo, fg)}</g></svg>\n'
    )


def lockup_geometry(logo: dict, wm: dict) -> dict:
    s = logo["lockup_cap"] / wm["cap_height"]
    x0, _, x1, _ = wm["bounds"]
    tx = 90 + logo["lockup_gap"] - x0 * s
    ty = 39 - (wm["cap_height"] / 2) * s  # centre the capitals on the mark's box
    width = 90 + logo["lockup_gap"] + (x1 - x0) * s
    return dict(s=s, tx=tx, ty=ty, width=width)


def svg_lockup(logo: dict, wm: dict, color: str, inline: bool = False) -> str:
    g = lockup_geometry(logo, wm)
    attrs = ('class="q-logo" aria-label="Quadrant"' if inline
             else f'xmlns="http://www.w3.org/2000/svg" width="{g["width"]:.0f}" height="78"')
    title = "" if inline else "<title>Quadrant</title>"
    return (
        f'<svg {attrs} viewBox="0 0 {g["width"]:.1f} 78" role="img">{title}'
        f'<g transform="translate(-5 -5)" fill="none">{mark_shapes(logo, color)}</g>'
        f'<path transform="translate({g["tx"]:.2f} {g["ty"]:.2f}) scale({g["s"]:.5f})" fill="{color}" d="{wm["d"]}"/>'
        "</svg>" + ("" if inline else "\n")
    )


def build_assets(data: dict, wm: dict) -> dict[str, str]:
    logo, c = data["logo"], data["colors"]
    ink, bay = c["ink"]["light"], c["primary"]["light"]
    return {
        "assets/mark.svg": svg_mark(logo, ink),
        "assets/mark-reversed.svg": svg_mark(logo, "#FFFFFF"),
        "assets/mark-primary.svg": svg_mark(logo, bay),
        "assets/logo-horizontal.svg": svg_lockup(logo, wm, ink),
        "assets/logo-horizontal-reversed.svg": svg_lockup(logo, wm, "#FFFFFF"),
        "assets/favicon.svg": svg_favicon(logo, bay, "#FFFFFF"),
        "assets/app-icon.svg": svg_app_icon(logo, bay, "#FFFFFF"),
    }


